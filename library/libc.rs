//! The functions of the C library that everything else is built on.

extern "C" {
    pub fn malloc(size: usize) -> *mut u8;
    pub fn realloc(pointer: *mut u8, size: usize) -> *mut u8;
    pub fn free(pointer: *mut u8);
    pub fn memcpy(dest: *mut u8, src: *const u8, count: usize) -> *mut u8;
    pub fn memmove(dest: *mut u8, src: *const u8, count: usize) -> *mut u8;
    pub fn memcmp(a: *const u8, b: *const u8, count: usize) -> i32;
    pub fn write(fd: i32, data: *const u8, count: usize) -> isize;
    pub fn exit(code: i32) -> !;
    pub fn read(fd: i32, data: *mut u8, count: usize) -> isize;
    pub fn open(path: *const u8, flags: i32, ...) -> i32;
    pub fn close(fd: i32) -> i32;
    pub fn stat(path: *const u8, buffer: *mut u8) -> i32;
    pub fn fstat(fd: i32, buffer: *mut u8) -> i32;
    pub fn unlink(path: *const u8) -> i32;
    pub fn mkdir(path: *const u8, mode: u32) -> i32;
    pub fn rmdir(path: *const u8) -> i32;
    pub fn rename(from: *const u8, to: *const u8) -> i32;
    pub fn getenv(name: *const u8) -> *const u8;
    pub fn getcwd(buffer: *mut u8, size: usize) -> *mut u8;
    pub fn strerror(code: i32) -> *const u8;
    pub fn strlen(text: *const u8) -> usize;
    pub fn __errno_location() -> *mut i32;
    pub fn pthread_create(thread: *mut u64, attributes: *const u8, start: fn(*mut u8) -> *mut u8, argument: *mut u8) -> i32;
    pub fn pthread_join(thread: u64, result: *mut *mut u8) -> i32;
    pub fn pthread_self() -> u64;
    pub fn pthread_key_create(key: *mut u32, destructor: *const u8) -> i32;
    pub fn pthread_getspecific(key: u32) -> *mut u8;
    pub fn pthread_setspecific(key: u32, value: *const u8) -> i32;
    pub fn _setjmp(buffer: *mut u64) -> i32;
    pub fn longjmp(buffer: *mut u64, value: i32) -> !;
    pub fn syscall(number: i64, ...) -> i64;
    pub fn sched_yield() -> i32;
    pub fn nanosleep(duration: *const u8, remaining: *mut u8) -> i32;
    pub fn clock_gettime(clock: i32, time: *mut u8) -> i32;
    pub fn sysconf(name: i32) -> i64;
    pub fn __gaia_atomic_load_1(address: *const u8) -> u8;
    pub fn __gaia_atomic_store_1(address: *mut u8, value: u8);
    pub fn __gaia_atomic_swap_1(address: *mut u8, value: u8) -> u8;
    pub fn __gaia_atomic_fetch_add_1(address: *mut u8, value: u8) -> u8;
    pub fn __gaia_atomic_compare_exchange_1(address: *mut u8, expected: u8, new: u8) -> u8;
    pub fn pthread_detach(thread: u64) -> i32;
    pub fn __gaia_atomic_load_4(address: *const u32) -> u32;
    pub fn __gaia_atomic_store_4(address: *mut u32, value: u32);
    pub fn __gaia_atomic_swap_4(address: *mut u32, value: u32) -> u32;
    pub fn __gaia_atomic_fetch_add_4(address: *mut u32, value: u32) -> u32;
    pub fn __gaia_atomic_compare_exchange_4(address: *mut u32, expected: u32, new: u32) -> u32;
    pub fn __gaia_atomic_load_8(address: *const u64) -> u64;
    pub fn __gaia_atomic_store_8(address: *mut u64, value: u64);
    pub fn __gaia_atomic_swap_8(address: *mut u64, value: u64) -> u64;
    pub fn __gaia_atomic_fetch_add_8(address: *mut u64, value: u64) -> u64;
    pub fn __gaia_atomic_compare_exchange_8(address: *mut u64, expected: u64, new: u64) -> u64;
    pub fn abort() -> !;
    pub fn getpid() -> i32;
    pub fn snprintf(buffer: *mut u8, size: usize, format: *const u8, ...) -> i32;
    pub fn strtod(text: *const u8, end: *mut *mut u8) -> f64;
    pub fn strtof(text: *const u8, end: *mut *mut u8) -> f32;
}

