fn main() {
    let mut s = String::from("Hello");
    s.push_str(", World"); s.push('!');
    println!("{} {} {}", s, s.len(), s.is_empty());
    println!("{} {}", s.to_uppercase(), s.to_lowercase());
    println!("{:?} {:?}", s.find("World"), s.find('z'));
    println!("{} {} {}", s.contains("lo, W"), s.starts_with("Hell"), s.ends_with('!'));
    println!("{}", s.replace("l", "L"));
    println!("{:?}", "a,b,,c".split(',').collect::<Vec<_>>());
    println!("{:?}", "  pad me  ".trim());
    println!("{:?} {:?}", "xxabcxx".trim_start_matches('x'), "xxabcxx".trim_end_matches("x"));
    println!("{:?}", "one two  three".split_whitespace().collect::<Vec<_>>());
    println!("{:?}", "line1\nline2\r\nline3".lines().collect::<Vec<_>>());
    println!("{}", "abc".chars().rev().collect::<String>());
    println!("{:?}", "héllo".char_indices().map(|(i, c)| (i, c)).collect::<Vec<_>>());
    println!("{} {}", "héllo".len(), "héllo".chars().count());
    println!("{}", "ab".repeat(3));
    println!("{:?}", "key=value".split_once('='));
    println!("{:?}", "a-b-c".splitn(2, '-').collect::<Vec<_>>());
    println!("{:?}", "a-b-c".rsplit('-').collect::<Vec<_>>());
    let mut t = String::with_capacity(8);
    t.insert(0, 'b'); t.insert_str(0, "a"); t.push_str("cd");
    let popped = t.pop();
    println!("{} {:?}", t, popped);
    t.truncate(2); println!("{}", t);
    println!("{}", t.remove(0));
    let word = "hello"; println!("{} {}", &word[1..3], &word[..2]);
    println!("{}", "Zebra" < "apple");
    println!("{:?}", "a1b2c3".chars().filter(|c| c.is_ascii_digit()).collect::<String>());
    println!("{:?}", "Hello".bytes().map(|b| b as u32).sum::<u32>());
    let parts = vec!["x", "y", "z"];
    println!("{} {}", parts.concat(), parts.join("/"));
    println!("{}", format!("{}-{}", "a", 1) + "tail");
    let owned: String = "slice".to_owned();
    println!("{}", owned.as_str().eq_ignore_ascii_case("SLICE"));
    println!("{:?}", "abc".as_bytes());
    println!("{}", String::from_utf8_lossy(&[72, 105]));
    println!("{:?}", "Mary had a lamb".matches('a').count());
    println!("{}", "tic-tac".replacen("t", "T", 1));
    println!("{:?}", "  x".strip_prefix("  "));
    println!("{}", "AbC".chars().all(|c| c.is_ascii_alphabetic()));
    let num = 255; println!("{}", format!("{:x}", num).to_uppercase());
    let mut chars: Vec<char> = "dcba".chars().collect(); chars.sort();
    println!("{}", chars.iter().collect::<String>());
    println!("{}", s.char_indices().filter(|(_, c)| *c == 'o').count());
}
