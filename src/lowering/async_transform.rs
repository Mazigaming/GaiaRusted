//! # Async Function Lowering Integration
//!
//! This module integrates the state_machine.rs module into the actual
//! compiler pipeline, transforming async functions into state machines.

use crate::async_await::state_machine::{
    generate_poll_method, generate_state_struct, AwaitPoint, StateId, StateMachine,
};
use crate::lowering::{HirExpression, HirItem, HirStatement, HirType};
use std::collections::HashMap;

/// Transform async functions into state machines
///
/// This function iterates through all HIR items and converts any async functions
/// into state machine implementations.
pub fn transform_async_functions(hir_items: Vec<HirItem>) -> Vec<HirItem> {
    let mut result = Vec::new();

    for item in hir_items {
        match item {
            HirItem::Function {
                name,
                generics,
                params,
                return_type,
                body,
                is_public,
                where_clause,
            } => {
                // Check if the function name suggests it's async (generated by async transformation)
                // or if it contains await expressions in its body
                let has_await = contains_await(&body);

                if has_await || name.contains("_async") || name.starts_with("__async_") {
                    // This is an async function - transform it to a state machine
                    let state_machine =
                        create_state_machine(&name, params.clone(), return_type.clone(), body);

                    // Generate the state struct
                    if let Ok(state_struct) = generate_state_struct(&state_machine) {
                        result.push(state_struct);
                    }

                    // Generate the poll method (as a new function)
                    if let Ok(HirItem::Function {
                        name,
                        params,
                        return_type,
                        body,
                        ..
                    }) = generate_poll_method(&state_machine)
                    {
                        // Create the poll method with the correct name
                        result.push(HirItem::Function {
                            name: format!("{}::poll", state_machine.func_name),
                            generics: vec![],
                            params,
                            return_type,
                            body,
                            is_public: false,
                            where_clause: vec![],
                        });
                    }

                    // Add a wrapper function that returns the Future
                    result.push(HirItem::Function {
                        name: name.clone(),
                        generics,
                        params,
                        return_type: Some(HirType::Named(format!(
                            "impl Future<Output = {}>",
                            return_type.clone().unwrap_or(HirType::Unknown)
                        ))),
                        body: vec![], // Empty body - will be handled at codegen
                        is_public,
                        where_clause,
                    });
                } else {
                    // Regular function - keep as is
                    result.push(HirItem::Function {
                        name,
                        generics,
                        params,
                        return_type,
                        body,
                        is_public,
                        where_clause,
                    });
                }
            }
            _ => {
                // Non-function items are kept as-is
                result.push(item);
            }
        }
    }

    result
}

/// Check if a body contains await expressions
fn contains_await(body: &[HirStatement]) -> bool {
    for stmt in body {
        if contains_await_stmt(stmt) {
            return true;
        }
    }
    false
}

fn contains_await_stmt(stmt: &HirStatement) -> bool {
    match stmt {
        HirStatement::Expression(expr) => contains_await_expr(expr),
        HirStatement::Let { init, .. } => contains_await_expr(init),
        HirStatement::Return(Some(expr)) => contains_await_expr(expr),
        HirStatement::If {
            then_body,
            else_body,
            ..
        } => {
            let in_then = then_body.iter().any(contains_await_stmt);
            let in_else = else_body
                .as_ref()
                .map(|b| b.iter().any(contains_await_stmt))
                .unwrap_or(false);
            in_then || in_else
        }
        HirStatement::While { body, .. } => body.iter().any(contains_await_stmt),
        HirStatement::For { body, .. } => body.iter().any(contains_await_stmt),
        _ => false,
    }
}

fn contains_await_expr(expr: &HirExpression) -> bool {
    match expr {
        HirExpression::Await { .. } => true,
        HirExpression::Call { args, .. } => args.iter().any(contains_await_expr),
        HirExpression::MethodCall { args, .. } => args.iter().any(contains_await_expr),
        HirExpression::BinaryOp { left, right, .. } => {
            contains_await_expr(left) || contains_await_expr(right)
        }
        HirExpression::If {
            condition,
            then_body,
            else_body,
            ..
        } => {
            let in_cond = contains_await_expr(condition);
            let in_then = then_body.iter().any(contains_await_stmt);
            let in_else = else_body
                .as_ref()
                .map(|b| b.iter().any(contains_await_stmt))
                .unwrap_or(false);
            in_cond || in_then || in_else
        }
        HirExpression::While { body, .. } => body.iter().any(contains_await_stmt),
        HirExpression::Match { arms, .. } => arms
            .iter()
            .any(|arm| arm.body.iter().any(contains_await_stmt)),
        HirExpression::Block(stmts, final_expr) => {
            let in_stmts = stmts.iter().any(contains_await_stmt);
            let in_expr = final_expr
                .as_ref()
                .map(|e| contains_await_expr(e))
                .unwrap_or(false);
            in_stmts || in_expr
        }
        _ => false,
    }
}

/// Create a state machine from an async function
fn create_state_machine(
    func_name: &str,
    params: Vec<(String, HirType)>,
    return_type: Option<HirType>,
    body: Vec<HirStatement>,
) -> StateMachine {
    // Extract await points from the function body
    let mut await_points = Vec::new();
    let mut local_vars = HashMap::new();
    let mut state_id = 0;

    extract_awaits_from_body(&body, &mut await_points, &mut local_vars, &mut state_id);

    StateMachine::new(
        func_name.to_string(),
        params,
        return_type.unwrap_or(HirType::Named("()".to_string())),
        await_points,
        local_vars,
    )
}

/// Recursively extract await points from the function body
fn extract_awaits_from_body(
    body: &[HirStatement],
    await_points: &mut Vec<AwaitPoint>,
    local_vars: &mut HashMap<String, HirType>,
    state_id: &mut usize,
) {
    for stmt in body {
        extract_awaits_from_stmt(stmt, await_points, local_vars, state_id);
    }
}

fn extract_awaits_from_stmt(
    stmt: &HirStatement,
    await_points: &mut Vec<AwaitPoint>,
    local_vars: &mut HashMap<String, HirType>,
    state_id: &mut usize,
) {
    match stmt {
        HirStatement::Let { name, ty, init, .. } => {
            local_vars.insert(name.clone(), ty.clone());
            extract_awaits_from_expr(init, await_points, local_vars, state_id);
        }
        HirStatement::Expression(expr) => {
            extract_awaits_from_expr(expr, await_points, local_vars, state_id);
        }
        HirStatement::Return(Some(expr)) => {
            extract_awaits_from_expr(expr, await_points, local_vars, state_id);
        }
        HirStatement::If {
            then_body,
            else_body,
            ..
        } => {
            for s in then_body {
                extract_awaits_from_stmt(s, await_points, local_vars, state_id);
            }
            if let Some(else_b) = else_body {
                for s in else_b {
                    extract_awaits_from_stmt(s, await_points, local_vars, state_id);
                }
            }
        }
        HirStatement::While { body, .. } => {
            for s in body {
                extract_awaits_from_stmt(s, await_points, local_vars, state_id);
            }
        }
        HirStatement::For { body, .. } => {
            for s in body {
                extract_awaits_from_stmt(s, await_points, local_vars, state_id);
            }
        }
        _ => {}
    }
}

fn extract_awaits_from_expr(
    expr: &HirExpression,
    await_points: &mut Vec<AwaitPoint>,
    local_vars: &mut HashMap<String, HirType>,
    state_id: &mut usize,
) {
    match expr {
        HirExpression::Await { value } => {
            let state_before = StateId(*state_id);
            *state_id += 1;
            let state_after = StateId(*state_id);

            await_points.push(AwaitPoint {
                id: await_points.len(),
                state_before,
                state_after,
                expr: *(*value).clone(),
                result_var: None,
                output_type: HirType::Unknown,
            });
        }
        HirExpression::Call { args, .. } => {
            for arg in args {
                extract_awaits_from_expr(arg, await_points, local_vars, state_id);
            }
        }
        HirExpression::MethodCall { args, .. } => {
            for arg in args {
                extract_awaits_from_expr(arg, await_points, local_vars, state_id);
            }
        }
        HirExpression::BinaryOp { left, right, .. } => {
            extract_awaits_from_expr(left, await_points, local_vars, state_id);
            extract_awaits_from_expr(right, await_points, local_vars, state_id);
        }
        HirExpression::If {
            then_body,
            else_body,
            ..
        } => {
            for s in then_body {
                extract_awaits_from_stmt(s, await_points, local_vars, state_id);
            }
            if let Some(else_b) = else_body {
                for s in else_b {
                    extract_awaits_from_stmt(s, await_points, local_vars, state_id);
                }
            }
        }
        HirExpression::While { body, .. } => {
            for s in body {
                extract_awaits_from_stmt(s, await_points, local_vars, state_id);
            }
        }
        HirExpression::Match { arms, .. } => {
            for arm in arms {
                for s in &arm.body {
                    extract_awaits_from_stmt(s, await_points, local_vars, state_id);
                }
            }
        }
        HirExpression::Block(stmts, final_expr) => {
            for s in stmts {
                extract_awaits_from_stmt(s, await_points, local_vars, state_id);
            }
            if let Some(e) = final_expr {
                extract_awaits_from_expr(e, await_points, local_vars, state_id);
            }
        }
        _ => {}
    }
}

