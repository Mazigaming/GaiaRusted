    #[test]
    fn test_transform_async_functions_large() {
        // Test with many functions
        let mut input_items = vec![];

        for i in 0..10 {
            input_items.push(HirItem::Function {
                name: format!("func_{}", i),
                generics: vec![],
                params: vec![],
                return_type: Some(HirType::Int32),
                body: vec![HirStatement::Return(Some(HirExpression::Integer(i as i64)))],
                is_public: false,
                where_clause: vec![],
            });
        }

        // Add one async function
        input_items.push(HirItem::Function {
            name: "async_func".to_string(),
            generics: vec![],
            params: vec![],
            return_type: Some(HirType::Int32),
            body: vec![
                HirStatement::Expression(HirExpression::Await {
                    value: Box::new(HirExpression::Integer(42)),
                }),
                HirStatement::Return(Some(HirExpression::Integer(0))),
            ],
            is_public: false,
            where_clause: vec![],
        });

        let result = transform_async_functions(input_items);

        // Should have 10 sync functions + async transformations
        assert!(
            result.len() >= 11,
            "Should preserve sync functions and add async transformations"
        );
    }

